def main():
    document = Document()

    style = document.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(10.5)

    for section in document.sections:
        section.top_margin = section.bottom_margin = Cm(2)
        section.left_margin = section.right_margin = Cm(2.2)

    title = document.add_paragraph()
    run = title.add_run("Κοστολόγηση Περιστατικών ΤΑ.ΕΠ. — μη δικαιούχοι ΓεΣΥ")
    run.bold = True
    run.font.size = Pt(15)
    run.font.color.rgb = NAVY

    subtitle = document.add_paragraph()
    run = subtitle.add_run("Εκκρεμή θέματα προς απόφαση")
    run.bold = True
    run.font.size = Pt(12)
    run.font.color.rgb = NAVY

    meta = document.add_paragraph()
    meta.add_run("Προς: ").bold = True
    meta.add_run("Μονάδα Ελέγχου Εσόδων\n")
    meta.add_run("Από: ").bold = True
    meta.add_run("Τμήμα Πληροφορικής\n")
    meta.add_run("Ημερομηνία: ").bold = True
    meta.add_run("14/09/2026\n")
    meta.add_run("Συνημμένο: ").bold = True
    meta.add_run("overlap_decision_list.xlsx")

    intro = document.add_paragraph()
    intro.add_run(
        f"Κατά την προετοιμασία του εργαλείου κοστολόγησης εντοπίστηκαν {len(ITEMS)} θέματα "
        f"που χρειάζονται απόφαση της Μονάδας. Κανένα δεν μπορεί να κριθεί από το Τμήμα "
        f"Πληροφορικής. Τα ευρήματα προκύπτουν από τα αρχεία που μας δόθηκαν και "
        f"αναπαράγονται αυτόματα από τα ίδια δεδομένα."
    )
    intro.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY

    counter = 0
    current_section = None
    for key, heading, body, asked in ITEMS:
        if key != current_section:
            current_section = key
            document.add_paragraph()
            section_title, section_note = SECTIONS[key]
            paragraph = document.add_paragraph()
            run = paragraph.add_run(section_title)
            run.bold = True
            run.font.size = Pt(12)
            run.font.color.rgb = NAVY
            note = document.add_paragraph()
            run = note.add_run(section_note)
            run.italic = True
            run.font.size = Pt(9.5)

        counter += 1
        paragraph = document.add_paragraph()
        run = paragraph.add_run(f"{counter}. {heading}")
        run.bold = True
        run.font.size = Pt(11)

        for block in body.split("\n\n"):
            text = document.add_paragraph(block)
            text.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
            text.paragraph_format.space_after = Pt(4)

        request = document.add_paragraph()
        run = request.add_run("Ζητούμενο: ")
        run.bold = True
        run.font.color.rgb = NAVY
        request.add_run(asked)

        answer = document.add_paragraph()
        run = answer.add_run("Απόφαση Μονάδας: ")
        run.bold = True
        answer.add_run("…………………………………………………………………………………………………………")
        answer.paragraph_format.space_after = Pt(14)

    document.add_page_break()
    paragraph = document.add_paragraph()
    run = paragraph.add_run("Σημείωση για τη διαδικασία")
    run.bold = True
    run.font.color.rgb = NAVY
    document.add_paragraph(
        "Οι τιμές είναι χρονικά οριοθετημένες. Κάθε κοστολόγηση χρησιμοποιεί την τιμή που "
        "ίσχυε κατά την ημερομηνία εξέτασης, όχι τη σημερινή, ώστε ένα περιστατικό του 2026 "
        "να ανακοστολογείται με τα ίδια αποτελέσματα και το 2031. Αλλαγή τιμής γίνεται με "
        "κλείσιμο της παλιάς περιόδου και άνοιγμα νέας, με καταγραφή του χρήστη και του "
        "εγγράφου απόφασης. Καμία τιμή δεν αντικαθίσταται επιτόπου."
    ).alignment = WD_ALIGN_PARAGRAPH.JUSTIFY

    path = DOCS / "TAEP_ekkremi_themata_Monada_Elegchou_Esodon.docx"
    document.save(path)
    print(f"wrote {path.relative_to(ROOT)}  ({counter} items)")
    return path


if __name__ == "__main__":
    main()
