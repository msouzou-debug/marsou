// ~40 fixture projects spread across the eleven org units roughly in
// proportion to the CAPEX-03 §3 row counts (113 real rows -> ~0.37
// scale here). Figures are obviously fake, round numbers. Ledgers follow
// the phase a project is in: no commitment before AWARDED, spend trailing
// commitment, forecast usually close to committed. RAG is computed once
// at authoring time by computeRag() below, using the documented rule:
//
// RULE (CAPEX-01 §7 forecast semantics):
//   RED   - committed > approvedBudget (overcommitted), or
//           forecast > approvedBudget * 1.05
//   AMBER - committed > 0.9 * approvedBudget AND
//           spent < 0.5 * (time elapsed / planned duration) * approvedBudget
//   GREEN - otherwise
//
// "Time elapsed" is measured against a fixed authoring reference date so
// the fixture is reproducible regardless of when tests run.
const RAG_REFERENCE_DATE = new Date("2026-09-01T00:00:00Z");

function daysBetween(a: Date, b: Date): number {
  return (b.getTime() - a.getTime()) / 86_400_000;
}

function timeElapsedFraction(start: Date, finish: Date, ref: Date): number {
  const total = daysBetween(start, finish);
  if (total <= 0) return 1;
  return Math.min(1, Math.max(0, daysBetween(start, ref) / total));
}

// RULE: see the comment above. Exported so buildPortfolio (portfolio.ts)
// and the exceptions list can classify a project without re-deriving the
// arithmetic from prose.
export function computeRag(
  approvedBudget: number,
  committed: number,
  spent: number,
  forecast: number,
  plannedStart: string,
  plannedFinish: string,
): { rag: "GREEN" | "AMBER" | "RED"; reasonKind: "OVERCOMMITTED" | "FORECAST_OVER" | "SPEND_LAG" | "NONE" } {
  const overcommitted = committed > approvedBudget;
  const forecastOver = forecast > approvedBudget * 1.05;
  if (overcommitted || forecastOver) {
    return { rag: "RED", reasonKind: overcommitted ? "OVERCOMMITTED" : "FORECAST_OVER" };
  }
  const committedPct = approvedBudget > 0 ? committed / approvedBudget : 0;
  const spentPct = approvedBudget > 0 ? spent / approvedBudget : 0;
  const elapsed = timeElapsedFraction(new Date(plannedStart), new Date(plannedFinish), RAG_REFERENCE_DATE);
  if (committedPct > 0.9 && spentPct < 0.5 * elapsed) {
    return { rag: "AMBER", reasonKind: "SPEND_LAG" };
  }
  return { rag: "GREEN", reasonKind: "NONE" };
}

